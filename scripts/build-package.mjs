/**
 * npm 包构建管线（2026-10-16 去 bun 化后的唯一发行构建）。
 *
 * 产物：server/dist/index.js —— esbuild 单文件 ESM bundle（web 静态资产经
 * static-assets.generated.ts 内嵌；hono/@hono/node-server 打入；引擎三包
 * external，运行时从安装方 node_modules 解析）。
 *
 * 步骤：
 *  1. web 前端构建（npm run build in web/，--server-only 跳过——开发迭代用）
 *  2. 生成 server/src/static-assets.generated.ts（内嵌资产模块，gitignore）
 *  3. esbuild bundle server/src/index.ts → server/dist/index.js
 *
 * 运行环境要求：node >= 24（node:sqlite）。
 */
import { spawnSync } from "node:child_process";
import { mkdirSync, readdirSync, readFileSync, realpathSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import * as esbuild from "esbuild";

const REPO_ROOT = realpathSync(join(import.meta.dirname, ".."));
const WEB_DIST = join(REPO_ROOT, "web", "dist");
const SERVER_SRC = join(REPO_ROOT, "server", "src");
const OUT_FILE = join(REPO_ROOT, "server", "dist", "index.js");
const GENERATED_TS = join(SERVER_SRC, "static-assets.generated.ts");
const SERVER_ONLY = process.argv.includes("--server-only");

function die(message) {
  console.error(`构建失败：${message}`);
  process.exit(1);
}

function run(cmd, cwd, label) {
  console.log(`==> ${label}: ${cmd.join(" ")}`);
  const r = spawnSync(cmd[0], cmd.slice(1), { cwd, stdio: "inherit" });
  if (r.status !== 0) die(`${label} 退出码 ${r.status}`);
}

// ---- 1. web 前端构建 ----
if (!SERVER_ONLY) {
  run(["npm", "run", "build"], join(REPO_ROOT, "web"), "web build");
  if (!exists(join(WEB_DIST, "index.html"))) die(`web 产物缺失 ${WEB_DIST}/index.html`);
}

// ---- 2. 生成内嵌资产模块（逻辑承自 scripts/build-binary.ts）----
function exists(p) {
  try {
    statSync(p);
    return true;
  } catch {
    return false;
  }
}

if (exists(WEB_DIST)) {
  const assetFiles = [];
  (function walk(dir) {
    for (const name of readdirSync(dir)) {
      const p = join(dir, name);
      if (statSync(p).isDirectory()) walk(p);
      else assetFiles.push(p);
    }
  })(WEB_DIST);

  let body = `// AUTO-GENERATED by scripts/build-package.mjs —— 请勿手改（.gitignore 已忽略）。
// web/dist 内嵌资产：静态托管优先走本模块（server/src/embedded-static.ts）。
export const EMBEDDED_STATIC = {
`;
  for (const f of assetFiles) {
    const rel = relative(WEB_DIST, f).split("\\").join("/");
    const buf = readFileSync(f);
    const binary = buf.includes(0);
    body += `  ${JSON.stringify(rel)}: { data: ${JSON.stringify(binary ? buf.toString("base64") : buf.toString("utf8"))}, binary: ${binary} },\n`;
  }
  body += "};\n";
  mkdirSync(SERVER_SRC, { recursive: true });
  writeFileSync(GENERATED_TS, body);
  console.log(`==> 内嵌资产模块：${assetFiles.length} 个文件 -> ${relative(REPO_ROOT, GENERATED_TS)}`);
} else if (!exists(GENERATED_TS)) {
  console.log("==> 跳过内嵌资产（web/dist 不存在且无生成模块；运行时回落磁盘静态目录）");
}

// ---- 3. esbuild bundle ----
mkdirSync(join(REPO_ROOT, "server", "dist"), { recursive: true });
const result = await esbuild.build({
  entryPoints: [join(SERVER_SRC, "index.ts")],
  bundle: true,
  platform: "node",
  target: "node24",
  format: "esm",
  outfile: OUT_FILE,
  // 引擎三包不打入：运行时从安装方 node_modules 解析（dist/index.js 内
  // createRequire/import 解析仍有效）；hono 系纯 JS 打入
  external: ["@code-yeongyu/senpi", "omo-ai"],
  banner: { js: "#!/usr/bin/env node" },
  logLevel: "info",
});
if (result.errors.length > 0) die("esbuild 报错");
console.log(`==> 构建完成：${relative(REPO_ROOT, OUT_FILE)}`);
