/**
 * 【已退役 2026-10-16】历史单二进制发行构建（bun compile 形态）。
 *
 * 当前发布走 npm 包：`npm run build`（scripts/build-package.mjs，esbuild 单文件），
 * 本脚本保留作历史参考与应急备胎——运行仍需 bun，且引擎闭包按 .bun isolated
 * 布局解析，在 npm 安装布局的仓库里需要先 `bun install` 才能跑通。
 *
 * W6 todo 29：单二进制发行包构建脚本。
 *
 * 产物结构（dist/）：
 *   ul-omo-webui                    单二进制（内嵌 web 静态资产 + 宿主全量 JS）
 *   engine/node_modules/           引擎运行时闭包（spawn 用，node 从 PATH 提供）
 *     omo-ai/                      omo 包本体（plugin/、bin/omo.js）
 *     @code-yeongyu/senpi/         官配 senpi 引擎（package.json 锁 2026.9.28-7，
 *                                  npm 包自带嵌套 node_modules，自包含闭包）
 *     @code-yeongyu/senpi-codemode/ senpi 兄弟依赖（hoisted 顶层）
 *
 * 发行形态说明（todo 30/31 引用，learnings.md 有结论）：
 * - "单二进制"承诺对宿主本体成立（web 静态资产内嵌、零磁盘依赖）；
 *   引擎是 spawn 出去的独立 node 子进程，其运行时文件无法静态编译进宿主，
 *   故发行包 = 单二进制 + engine/ 目录（偏离绝对单文件，已回报用户拍板）。
 * - 运行环境要求：PATH 上有 node（RpcClient 固定 spawn("node", cliPath)）。
 */
import { spawnSync } from "node:child_process";
import { cpSync, existsSync, mkdirSync, readdirSync, readFileSync, realpathSync, rmSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";

const REPO_ROOT = realpathSync(join(import.meta.dir, ".."));
const WEB_DIST = join(REPO_ROOT, "web", "dist");
const DIST = join(REPO_ROOT, "dist");
const OUT_BIN = join(DIST, "ul-omo-webui");
const GENERATED_TS = join(REPO_ROOT, "server", "src", "static-assets.generated.ts");

function die(message: string): never {
  console.error(`构建失败：${message}`);
  process.exit(1);
}

function run(cmd: string[], cwd: string, label: string): void {
  console.log(`==> ${label}: ${cmd.join(" ")}`);
  const r = spawnSync(cmd[0], cmd.slice(1), { cwd, stdio: "inherit" });
  if (r.status !== 0) die(`${label} 退出码 ${r.status}`);
}

// ---- 1. web 前端构建 ----
run(["bun", "run", "build"], join(REPO_ROOT, "web"), "web build");
if (!existsSync(join(WEB_DIST, "index.html"))) die(`web 产物缺失 ${WEB_DIST}/index.html`);

// ---- 2. 生成内嵌资产模块（server/src/static-assets.generated.ts，gitignore）----
const assetFiles: string[] = [];
(function walk(dir: string): void {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p);
    else assetFiles.push(p);
  }
})(WEB_DIST);

let body = `// AUTO-GENERATED by scripts/build-binary.ts —— 请勿手改（.gitignore 已忽略）。
// web/dist 内嵌资产：静态托管编译产物优先走本模块（server/src/embedded-static.ts）。
export interface StaticAsset { data: string; binary: boolean }
export const EMBEDDED_STATIC: Record<string, StaticAsset> = {
`;
for (const f of assetFiles) {
  const rel = relative(WEB_DIST, f).split("\\").join("/");
  const buf = readFileSync(f);
  const binary = buf.includes(0);
  body += `  ${JSON.stringify(rel)}: { data: ${JSON.stringify(binary ? buf.toString("base64") : buf.toString("utf8"))}, binary: ${binary} },\n`;
}
body += "};\n";
mkdirSync(join(REPO_ROOT, "server", "src"), { recursive: true });
writeFileSync(GENERATED_TS, body);
console.log(`==> 内嵌资产模块：${assetFiles.length} 个文件 -> ${relative(REPO_ROOT, GENERATED_TS)}`);

// ---- 3. 引擎运行时闭包部署（dist/engine/node_modules/）----
// 源路径按源码形态的官配解析链找（与 process-manager/senpi-adapter 同语义）：
// senpi 官配 = .bun/omo-ai@<ver>/node_modules/@code-yeongyu/senpi（realpath 真身）
const omoAiVersion = "5.1.0";
const bunDir = join(REPO_ROOT, "node_modules", ".bun");
const senpiCandidates = [
  join(bunDir, `omo-ai@${omoAiVersion}`, "node_modules", "@code-yeongyu", "senpi", "dist", "bundle", "cli.js"),
  join(REPO_ROOT, "server", "node_modules", "omo-ai", "node_modules", "@code-yeongyu", "senpi", "dist", "bundle", "cli.js"),
  join(REPO_ROOT, "node_modules", "omo-ai", "node_modules", "@code-yeongyu", "senpi", "dist", "bundle", "cli.js"),
];
const senpiCli = senpiCandidates.find((c) => existsSync(c));
if (!senpiCli) die(`官配 senpi 引擎 cli 未找到（候选：${senpiCandidates.join(" / ")}）`);
// 先 realpath 解析整条 symlink 链（.bun isolated 布局），再对真身路径做纯字符串回退：
// cli.js -> bundle -> dist -> senpi 包根
const senpiPkg = join(realpathSync(senpiCli), "..", "..", "..");

const omoRoot = realpathSync(join(REPO_ROOT, "server", "node_modules", "omo-ai"));
const codemodeSrc = join(senpiPkg, "node_modules", "@code-yeongyu", "senpi-codemode");

console.log(`==> 引擎闭包：senpi=${relative(REPO_ROOT, senpiPkg)} omo-ai=${relative(REPO_ROOT, omoRoot)}`);
rmSync(join(DIST, "engine"), { recursive: true, force: true });
const engineNm = join(DIST, "engine", "node_modules");
mkdirSync(join(engineNm, "@code-yeongyu"), { recursive: true });
// dereference：展平符号链接（bun isolated 布局的 hoisted symlink），拷出即自包含
cpSync(omoRoot, join(engineNm, "omo-ai"), { recursive: true, dereference: true });
cpSync(senpiPkg, join(engineNm, "@code-yeongyu", "senpi"), { recursive: true, dereference: true });
if (existsSync(codemodeSrc)) {
  cpSync(codemodeSrc, join(engineNm, "@code-yeongyu", "senpi-codemode"), { recursive: true, dereference: true });
}
if (!existsSync(join(engineNm, "@code-yeongyu", "senpi", "dist", "bundle", "cli.js"))) {
  die("引擎闭包部署后 cli.js 缺失");
}

// ---- 4. 单二进制编译（内嵌静态资产随 server/src/static-assets.generated.ts 打入）----
rmSync(OUT_BIN, { force: true });
run(["bun", "build", "--compile", "src/index.ts", "--outfile", OUT_BIN], join(REPO_ROOT, "server"), "bun compile");

// ---- 5. 产物统计 ----
function dirSize(dir: string): number {
  let total = 0;
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    total += statSync(p).isDirectory() ? dirSize(p) : statSync(p).size;
  }
  return total;
}
const mb = (n: number): string => `${(n / 1024 / 1024).toFixed(1)} MB`;
console.log(`==> 产物清单（${relative(REPO_ROOT, DIST)}/）`);
console.log(`    ul-omo-webui        ${mb(statSync(OUT_BIN).size)}`);
console.log(`    engine/node_modules ${mb(dirSize(join(DIST, "engine")))}`);
console.log("构建完成。运行要求：PATH 上有 node；数据目录缺省落可执行文件旁 data/。");
